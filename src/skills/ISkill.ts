import type { ITool } from "../tools/ITool"

/**
 * Навык — это пакет контекстных знаний: инструкции, которые
 * должна следовать модель, необязательные инструменты и триггеры
 * активации.
 *
 * Навыки — это не код, а предметные знания, вставляемые в
 * системный запрос. Примеры: "работа с Effect TypeScript",
 * "написание тестов на Rust".
 */
export interface ISkill {
  /** Уникальное имя навыка. */
  name: string

  /** Краткое описание, отображаемое пользователю. */
  description: string

  /** Ключевые слова для активации навыка. Сравниваются с пользовательскими запросами. */
  triggers: string[]

  /**
   * Полные инструкции, вставляемые в системный запрос при активации навыка.
   * Это то, что делает модель "компетентной" в конкретной области.
   */
  instructions: string

  /** Необязательные инструменты. Зарегистрируются в реестре инструментов при активации. */
  tools?: ITool[]

  /** Приоритет для сортировки при совпадении нескольких навыков. Выше — предпочтительнее. */
  priority?: number
}
