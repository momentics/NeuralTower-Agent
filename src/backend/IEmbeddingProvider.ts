/**
 * Интерфейс провайдера эмбеддингов.
 *
 * Эмбеддинги используются для преобразования текста
 * в числовые векторы, которые затем хранятся в
 * векторном хранилище для семантического поиска.
 */

/**
 * Провайдер эмбеддингов.
 */
export interface IEmbeddingProvider {
  /**
   * Создать эмбеддинги для списка текстов.
   * @param texts тексты для эмбеддинга
   * @returns массив векторов (один на каждый текст)
   */
  embed(texts: string[]): Promise<number[][]>

  /**
   * Поддерживает ли провайдер эмбеддинги.
   */
  isAvailable(): boolean

  /**
   * Размер вектора эмбеддинга.
   */
  dimension(): number

  /**
   * Имя модели эмбеддинга.
   */
  modelName(): string
}

/**
 * Конфигурация провайдера эмбеддингов.
 */
export interface IEmbeddingProviderConfig {
  /** Возвращает текущий адрес бэкенда (читается в момент запроса, а не при конструировании). */
  getBaseUrl: () => string

  /** Модель эмбеддинга. */
  model: string

  /** Размер батча для эмбеддинга. */
  batchSize: number

  /** Таймаут в миллисекундах. */
  timeoutMs: number
}
